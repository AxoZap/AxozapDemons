function parseDemonData(data: string) {
  const lines = data.trim().split('\n');
  const demons = [];
  
  for (const line of lines) {
    const trimmedLine = line.trim();
    if (!trimmedLine) continue; // Skip empty lines
    
    const parts = trimmedLine.split('\t');
    if (parts.length < 6) continue;
    
    const name = parts[0].trim();
    const difficulty = parts[1].trim() as 'Easy' | 'Medium' | 'Hard' | 'Insane' | 'Extreme';
    const rating = parts[2].trim() as 'Star' | 'Moon';
    const gauntlet = parts[3].trim() === 'TRUE';
    const weekly = parts[4].trim() === 'TRUE';
    const event = parts[5].trim() === 'TRUE';
    const attempts = parts[6] ? parseInt(parts[6].trim()) : undefined;
    
    demons.push({
      name,
      difficulty,
      rating,
      gauntlet,
      weekly,
      event,
      ...(attempts && { attempts })
    });
  }
  
  console.log(`Parsed ${demons.length} demons from data`);
  return demons;
}

export async function bulkImportDemons(password: string) {
  const demons = parseDemonData(rawData);
  
  console.log(`📊 Parsed ${demons.length} demons from spreadsheet`);
  console.log('First 5 demons:', demons.slice(0, 5));
  console.log('Last 5 demons:', demons.slice(-5));
  
  // Get projectId and publicAnonKey from the same place as App.tsx
  const { projectId, publicAnonKey } = await import('./utils/supabase/info');
  
  const response = await fetch(`https://${projectId}.supabase.co/functions/v1/make-server-7e6e6986/demons/bulk`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${publicAnonKey}`,
    },
    body: JSON.stringify({ password, demons }),
  });
  
  if (response.ok) {
    const result = await response.json();
    console.log(`✅ Successfully imported ${result.count} demons!`);
    console.log(`⚠️ If you see more than ${demons.length} demons in your list, you may need to Clear All first!`);
    return result;
  } else {
    const error = await response.json();
    console.error('❌ Import failed:', error);
    throw new Error(error.error || 'Failed to import demons');
  }
}

